function renderIndexDts(hc: HelperShape, intg: HelperShape): string {
  const clientFields = PLUGINS.map(
    (p) => `  ${propertyKey(p.pluginId)}: InferClient<typeof ${p.apiExport}>;`,
  ).join("\n");
  const typeImports = PLUGINS.map(
    (p) => `import type { ${p.apiExport} } from "${p.pkg}";`,
  ).join("\n");
  // Value re-export of every contract ClientDefinition, one per package.
  const apiReexports = PLUGINS.map(
    (p) => `export { ${p.apiExport} } from "${p.pkg}";`,
  ).join("\n");

  return (
    GENERATED_BANNER +
    "\n" +
    'import type { InferClient } from "@checkstack/common";\n' +
    typeImports +
    "\n\n" +
    "export interface CheckstackClient {\n" +
    clientFields +
    "\n}\n\n" +
    "export interface CreateCheckstackClientOptions {\n" +
    "  baseUrl: string;\n" +
    "  headers?: Record<string, string>;\n" +
    "}\n\n" +
    "export declare function createCheckstackClient(\n" +
    "  options: CreateCheckstackClientOptions,\n" +
    "): CheckstackClient;\n\n" +
    apiReexports +
    "\n\n" +
    "// Script-authoring helpers (also available under the per-subpath exports).\n" +
    hc.resultInterface +
    "\n\n" +
    hc.contextInterface +
    "\n\n" +
    intg.resultInterface +
    "\n\n" +
    intg.contextInterface +
    "\n\n" +
    "export declare function " +
    hc.defineSignature +
    "\n" +
    "export declare function " +
    intg.defineSignature +
    "\n" +
    `export type {\n  ${hc.resultName},\n  ${hc.contextName},\n  ${intg.resultName},\n  ${intg.contextName},\n};\n\n` +
    'export type { InferClient, ClientDefinition } from "@checkstack/common";\n'
  );
}

function renderEditorBundle(hc: HelperShape, intg: HelperShape): string {
  return (
    GENERATED_BANNER +
    "\n" +
    "// Combined ambient declarations served ONLY by the version-keyed editor\n" +
    "// route and mounted into Monaco. NOT the `exports`-resolved declarations\n" +
    "// (those are the per-subpath generated/*.d.ts). Declares the subpath module\n" +
    "// names only - bare names are intentionally absent so an old import errors.\n" +
    "//\n" +
    "// Every declaration is module-scoped (no top-level globals): the editor\n" +
    "// mounts this bundle alongside scriptContext.ts, which owns the global\n" +
    "// `defineHealthCheck` / `defineIntegration` + schema-narrowed context types\n" +
    "// (plan §6.2). Top-level globals here would duplicate those and error.\n" +
    "\n" +
    renderHelperAmbient(hc) +
    "\n" +
    renderHelperAmbient(intg) +
    "\n" +
    renderRootAmbient(hc, intg)
  );
}

/**
 * Renders the runtime `src/editor-bundle.ts` module. It exports the editor
 * bundle `.d.ts` text AND the stamped release version as plain string
 * constants so the backend SDK-types route can serve them WITHOUT a filesystem
 * read (deploy-safe: it's real bundled TS, not a runtime `fs` lookup of a
 * `.d.ts` under `generated/`). Served by `script-packages-backend`'s
 * version-keyed route and mounted into Monaco (plan §6.1).
 *
 * `JSON.stringify` escapes the multi-line declaration text into a safe
 * double-quoted string literal (newlines become `\n`, backticks/`${` are
 * inert), so the emitted module is always valid TS regardless of the bundle's
 * content.
 */
function renderEditorBundleModule({ bundle }: { bundle: string }): string {
  return (
    GENERATED_BANNER +
    "\n" +
    "// Runtime-importable copy of the editor bundle, served by the\n" +
    "// @checkstack/sdk editor-types backend route (plan §6.1). Imported by\n" +
    "// the BACKEND only - it embeds the full bundle text, which the frontend\n" +
    "// must NOT bundle (it fetches the bundle live; see ./version.ts).\n" +
    "\n" +
    "/** The combined ambient `.d.ts` the in-app editor mounts into Monaco. */\n" +
    "export const SDK_EDITOR_BUNDLE_DTS = " +
    JSON.stringify(bundle) +
    ";\n\n" +
    'export { SDK_RELEASE_VERSION } from "./version.ts";\n'
  );
}

