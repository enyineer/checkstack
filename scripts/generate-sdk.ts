/**
 * A TS object-property key must be quoted when it is not a valid identifier
 * (e.g. `script-packages` contains a hyphen).
 */
function propertyKey(key: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
}

/**
 * Extracts a top-level `interface <name> { ... }` block (with its leading
 * JSDoc comment, if any) from the text produced by a `_internals` helper
 * builder. We reuse the SAME source text the editor uses, so the SDK's
 * runtime types can never drift from the in-editor declarations.
 */
function extractInterface({
  source,
  name,
}: {
  source: string;
  name: string;
}): string {
  const marker = `interface ${name} {`;
  const start = source.indexOf(marker);
  if (start === -1) {
    throw new Error(`Could not find "interface ${name}" in helper source.`);
  }

  // Walk back over an immediately-preceding JSDoc block (only whitespace may
  // separate it from the `interface` keyword). Find the LAST `*/` before the
  // interface and the `/**` that opens that same block - NOT an earlier one,
  // so we don't swallow a previous interface's text.
  let blockStart = start;
  const before = source.slice(0, start);
  const trimmedLen = before.replace(/\s+$/, "").length;
  if (before.slice(trimmedLen - 2, trimmedLen) === "*/") {
    const openIdx = before.lastIndexOf("/**", trimmedLen - 2);
    if (openIdx !== -1) {
      blockStart = openIdx;
    }
  }

  // Brace-match from the opening `{` of the interface to its close.
  const braceOpen = source.indexOf("{", start);
  let depth = 0;
  let end = -1;
  for (let i = braceOpen; i < source.length; i++) {
    const ch = source[i];
    if (ch === "{") depth++;
    else if (ch === "}") {
      depth--;
      if (depth === 0) {
        end = i + 1;
        break;
      }
    }
  }
  if (end === -1) {
    throw new Error(`Unbalanced braces extracting "interface ${name}".`);
  }

  return source.slice(blockStart, end).trim();
}

interface HelperShape {
  /** Subpath segment, e.g. "healthcheck". */
  subpath: string;
  /** The helper function name, e.g. "defineHealthCheck". */
  fnName: string;
  /** `interface ...Result { ... }` text. */
  resultInterface: string;
  /** `interface ...Context { ... }` text. */
  contextInterface: string;
  /** Result type name. */
  resultName: string;
  /** Context type name. */
  contextName: string;
  /** The generic `defineX<...>(value: T): T` declaration body (no `declare`). */
  defineSignature: string;
}

/**
 * Builds the structural pieces for one helper subpath by reusing the editor's
 * own `_internals` builder text (single source of truth).
 */
function buildHelperShape({
  subpath,
  fnName,
  resultName,
  contextName,
  builderText,
}: {
  subpath: string;
  fnName: string;
  resultName: string;
  contextName: string;
  builderText: string;
}): HelperShape {
  const resultInterface = extractInterface({ source: builderText, name: resultName });
  const contextInterface = extractInterface({ source: builderText, name: contextName });

  // Extract the generic `declare function <fn><...>(value: T): T;` block and
  // strip the `declare ` so it can back both a runtime function (in src) and a
  // declaration (in generated .d.ts).
  const declMarker = `declare function ${fnName}`;
  const declStart = builderText.indexOf(declMarker);
  if (declStart === -1) {
    throw new Error(`Could not find "declare function ${fnName}".`);
  }
  const declEnd = builderText.indexOf(";", declStart);
  if (declEnd === -1) {
    throw new Error(`Unterminated "declare function ${fnName}".`);
  }
  // Strip the leading `declare function ` so `defineSignature` is just
  // `<fn><...>(value: T): T;` - callers re-add the appropriate prefix
  // (`export function`, `export declare function`, or `declare function`).
  const defineSignature = builderText
    .slice(declStart, declEnd + 1)
    .replace(/^declare\s+function\s+/, "")
    .trim();

  return {
    subpath,
    fnName,
    resultInterface,
    contextInterface,
    resultName,
    contextName,
    defineSignature,
  };
}

/**
 * Renders the runtime `src/<subpath>.ts` for a helper: the interfaces plus the
 * identity-function implementation (behaviorally identical to the in-app
 * `esm-script-runner` rewrite, see plan §3.7/§6.3).
 */
function renderHelperSrc(shape: HelperShape): string {
  const { fnName, resultName, contextName, resultInterface, contextInterface } =
    shape;
  // `defineSignature` is `defineX<T extends ...>(value: T): T;` - turn it into a
  // function definition that returns its argument unchanged.
  const fnDef = shape.defineSignature.replace(/;$/, " {\n  return value;\n}");
  return (
    GENERATED_BANNER +
    "\n" +
    resultInterface +
    "\n\n" +
    contextInterface +
    "\n\n" +
    // Re-export the context + result interfaces as types so the package barrel
    // (`export * from "./<subpath>.ts"`) surfaces them. Without this, only the
    // `defineX` function is re-exported and `HealthCheckScriptContext` /
    // `IntegrationScriptContext` are unreachable to consumers (plan Phase-1
    // MINOR: `export type` the helper context interfaces from the runtime barrel).
    `export type { ${resultName}, ${contextName} };\n\n` +
    "/**\n" +
    ` * Identity helper for ${fnName} scripts. The value is returned unchanged at\n` +
    " * runtime - the function only narrows what `export default` may be so\n" +
    " * mistakes are caught before the script runs. Matches the in-app runner's\n" +
    " * injected helper body exactly (esm-script-runner identity rewrite).\n" +
    " */\n" +
    "export function " +
    fnDef +
    "\n"
  );
}

/**
 * Renders the per-subpath `generated/<subpath>.d.ts` - the `exports`-`types`
 * target external `npm install` resolves under node16/nodenext/bundler. Its
 * top-level exports ARE exactly that subpath's surface.
 */
function renderHelperDts(shape: HelperShape): string {
  const { resultName, contextName, resultInterface, contextInterface, defineSignature } =
    shape;
  return (
    GENERATED_BANNER +
    "\n" +
    resultInterface +
    "\n\n" +
    contextInterface +
    "\n\n" +
    "export declare function " +
    defineSignature +
    "\n\n" +
    `export type { ${resultName}, ${contextName} };\n`
  );
}

/** Re-indents a block of text by `spaces` (used to nest interfaces inside a
 * `declare module { ... }` block). Blank lines stay blank. */
function indentBlock(text: string, spaces: number): string {
  const pad = " ".repeat(spaces);
  return text
    .split("\n")
    .map((line) => (line.length > 0 ? pad + line : line))
    .join("\n");
}

/**
 * Renders the SELF-CONTAINED ambient `declare module "@checkstack/sdk/<subpath>"`
 * block for the editor bundle. The interfaces and the `defineX` function live
 * INSIDE the module block (exported from it) rather than as top-level globals.
 *
 * Why module-internal and NOT top-level globals: the editor mounts this bundle
 * ALONGSIDE the per-editor `scriptContext.ts` declarations, which ALREADY
 * declare the global `defineHealthCheck` / `defineIntegration` + the
 * schema-narrowed `HealthCheckScriptContext` / `IntegrationScriptContext`
 * (their raison d'être, plan §6.2). Re-declaring those as top-level globals
 * here too would produce duplicate-identifier / duplicate-implementation errors
 * in the shared TS language service. Keeping them module-scoped means
 * `import { defineHealthCheck } from "@checkstack/sdk/healthcheck"` resolves
 * cleanly while no-import autocomplete still works via scriptContext's globals.
 */
function renderHelperAmbient(shape: HelperShape): string {
  const { subpath, resultInterface, contextInterface, defineSignature } = shape;
  return (
    `declare module "@checkstack/sdk/${subpath}" {\n` +
    indentBlock(resultInterface, 2) +
    "\n\n" +
    indentBlock(contextInterface, 2) +
    "\n\n" +
    indentBlock("export function " + defineSignature, 2) +
    "\n" +
    `  export type { ${shape.resultName}, ${shape.contextName} };\n` +
    "}\n"
  );
}

/**
 * Renders the root `declare module "@checkstack/sdk"` block for the editor
 * bundle. It re-exports the helper symbols from the subpath modules (so
 * `import { defineHealthCheck } from "@checkstack/sdk"` also resolves in the
 * editor) and declares the typed-client factory surface. Self-contained: no
 * top-level globals, so it cannot collide with scriptContext (see
 * `renderHelperAmbient`).
 */
function renderRootAmbient(hc: HelperShape, intg: HelperShape): string {
  return (
    'declare module "@checkstack/sdk" {\n' +
    `  export { defineHealthCheck } from "@checkstack/sdk/healthcheck";\n` +
    `  export type { ${hc.resultName}, ${hc.contextName} } from "@checkstack/sdk/healthcheck";\n` +
    `  export { defineIntegration } from "@checkstack/sdk/integration";\n` +
    `  export type { ${intg.resultName}, ${intg.contextName} } from "@checkstack/sdk/integration";\n` +
    "  export interface CreateCheckstackClientOptions {\n" +
    "    baseUrl: string;\n" +
    "    headers?: Record<string, string>;\n" +
    "  }\n" +
    "  /** The fully-typed Checkstack API client (one entry per plugin id). */\n" +
    "  export type CheckstackClient = Record<string, unknown>;\n" +
    "  /** Build a typed Checkstack client over the REST/OpenAPI surface. */\n" +
    "  export function createCheckstackClient(\n" +
    "    options: CreateCheckstackClientOptions,\n" +
    "  ): CheckstackClient;\n" +
    "}\n"
  );
}

function renderContracts(): string {
  // All *Api symbols come from distinct packages; emit one re-export per package.
  const importLines = PLUGINS.map(
    (p) => `export { ${p.apiExport} } from "${p.pkg}";`,
  ).join("\n");
  return (
    GENERATED_BANNER +
    "\n" +
    "/**\n" +
    " * Re-export of every per-plugin oRPC contract `ClientDefinition`. Each is\n" +
    " * the source-of-truth API surface the running backend serves at\n" +
    " * `/rest/:pluginId/*`.\n" +
    " */\n" +
    importLines +
    "\n"
  );
}

function renderClient(): string {
  const valueImports = PLUGINS.map(
    (p) => `import { ${p.apiExport} } from "${p.pkg}";`,
  ).join("\n");

  const clientFields = PLUGINS.map(
    (p) => `  ${propertyKey(p.pluginId)}: InferClient<typeof ${p.apiExport}>;`,
  ).join("\n");

  // The OpenAPILink needs the SAME nested contract router the backend serves
  // (`rootRpcRouter[pluginId]`, prefix `/rest`) so it can map procedure calls
  // to REST routes. Assemble it from each ClientDefinition's `.contract`.
  const contractFields = PLUGINS.map(
    (p) => `  ${propertyKey(p.pluginId)}: ${p.apiExport}.contract,`,
  ).join("\n");

  return (
    GENERATED_BANNER +
    "\n" +
    'import { createORPCClient } from "@orpc/client";\n' +
    'import { OpenAPILink } from "@orpc/openapi-client/fetch";\n' +
    'import type { InferClient } from "@checkstack/common";\n' +
    valueImports +
    "\n\n" +
    "/**\n" +
    " * The fully-typed Checkstack API client. One entry per plugin id, mirroring\n" +
    " * the backend's root oRPC router nesting (`rootRpcRouter[pluginId]`). Each\n" +
    " * value is the contract's inferred client (`InferClient`).\n" +
    " */\n" +
    "export interface CheckstackClient {\n" +
    clientFields +
    "\n}\n\n" +
    "/** Options for {@link createCheckstackClient}. */\n" +
    "export interface CreateCheckstackClientOptions {\n" +
    "  /** Base URL of the Checkstack REST surface, e.g. `https://host/rest`. */\n" +
    "  baseUrl: string;\n" +
    "  /** Extra request headers, e.g. API-key / bearer auth. */\n" +
    "  headers?: Record<string, string>;\n" +
    "}\n\n" +
    "/**\n" +
    " * The nested contract router mirroring the backend's `/rest/:pluginId/*`\n" +
    " * surface. Passed to {@link OpenAPILink} so calls map to REST routes.\n" +
    " */\n" +
    "const checkstackContract = {\n" +
    contractFields +
    "\n};\n\n" +
    "/**\n" +
    " * Build a typed Checkstack client over the REST/OpenAPI surface\n" +
    " * (`/rest/:pluginId/*`). Each plugin is reachable under its plugin id.\n" +
    " */\n" +
    "export function createCheckstackClient({\n" +
    "  baseUrl,\n" +
    "  headers,\n" +
    "}: CreateCheckstackClientOptions): CheckstackClient {\n" +
    "  // Strip trailing slashes without a backtracking-prone regex\n" +
    "  // (`/\\/+$/` is O(n^2) on inputs like \"////...x\" - CodeQL js/polynomial-redos).\n" +
    "  let normalizedBase = baseUrl;\n" +
    "  while (normalizedBase.endsWith(\"/\")) normalizedBase = normalizedBase.slice(0, -1);\n" +
    "  const link = new OpenAPILink(checkstackContract, {\n" +
    "    url: normalizedBase,\n" +
    "    headers: () => headers ?? {},\n" +
    "  });\n" +
    "  // oRPC's `createORPCClient` constrains its type param to an index-signature\n" +
    "  // `NestedClient`, which a fixed-key interface like `CheckstackClient` cannot\n" +
    "  // satisfy structurally. The runtime client IS the CheckstackClient shape\n" +
    "  // (one entry per plugin contract), so cast through the oRPC-inferred client.\n" +
    "  // Mirrors core/frontend/src/apis/rpc-api.ts.\n" +
    "  return createORPCClient(link) as unknown as CheckstackClient;\n" +
    "}\n"
  );
}

