/**
 * Generates the `@checkstack/sdk` package from the platform's source of
 * truth: the per-plugin oRPC contracts (`*Api` `ClientDefinition`s exported
 * from each `@checkstack/<plugin>-common`) and the script-authoring helper
 * type builders (`scriptContext.ts` `_internals`).
 *
 * Emits (all committed):
 *   core/sdk/package.json            - name + version STAMPED from @checkstack/release
 *   core/sdk/src/contracts.ts        - re-export of every *Api ClientDefinition
 *   core/sdk/src/client.ts           - CheckstackClient type + createCheckstackClient
 *   core/sdk/src/healthcheck.ts      - defineHealthCheck identity runtime + types
 *   core/sdk/src/integration.ts      - defineIntegration identity runtime + types
 *   core/sdk/src/index.ts            - root re-export surface
 *   core/sdk/src/version.ts          - stamped release version (frontend-safe)
 *   core/sdk/src/editor-bundle.ts    - runtime editor bundle (backend-only)
 *   core/sdk/generated/index.d.ts        - root subpath `types` target
 *   core/sdk/generated/healthcheck.d.ts  - ./healthcheck subpath `types` target
 *   core/sdk/generated/integration.d.ts  - ./integration subpath `types` target
 *   core/sdk/generated/editor-bundle.d.ts - combined ambient .d.ts (editor only)
 *
 * Modes:
 *   - default: write the generated files to disk.
 *   - --check: regenerate to in-memory buffers and diff against the committed
 *     files; exit 1 on drift. Run in CI so a contract change without a
 *     regenerated SDK fails (mirrors `typecheck:references:check`).
 *
 * Idempotent: a fresh run on unchanged inputs produces byte-identical output.
 *
 * Single source of truth: the helper interface bodies AND the editor ambient
 * bundle are both derived from the SAME `scriptContext.ts` `_internals`
 * builders, so the runtime `src/*.ts`, the per-subpath `generated/*.d.ts`, and
 * the editor bundle can never drift from the in-editor declarations.
 */

